import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { afterAll, describe, expect, it } from "vitest";

import {
  ATTRIBUTION_RULES,
  attributionProblems,
  baseRef,
  commitAttribution,
  type Git,
  processGit,
  processIo,
  proposedCommits,
  pullRequestMessages,
  stripGitComments,
} from "./commit-attribution";

const made: string[] = [];
afterAll(() => {
  for (const dir of made) rmSync(dir, { recursive: true, force: true });
});

function tempDir(): string {
  const dir = mkdtempSync(path.join(tmpdir(), "commit-attribution-"));
  made.push(dir);
  return dir;
}

/** A repository whose `main` has one commit, with `messages` committed on a branch after it. */
function repository(messages: readonly string[]): string {
  const root = tempDir();
  const git = (...args: string[]) =>
    execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@example.com", ...args], {
      cwd: root,
      stdio: "ignore",
    });
  git("init", "--quiet", "--initial-branch=main");
  git("commit", "--quiet", "--allow-empty", "-m", "Start");
  git("switch", "--quiet", "-c", "feature");
  for (const message of messages) git("commit", "--quiet", "--allow-empty", "-m", message);
  return root;
}

function check(text: string): string[] {
  return attributionProblems({ label: "commit abc1234", text });
}

describe("the rules", () => {
  it.each(ATTRIBUTION_RULES)("$name catches its example", (rule) => {
    expect(rule.pattern.test(rule.example)).toBe(true);
    expect(check(rule.example)).toEqual([`commit abc1234 line 1: ${rule.name}: ${rule.example}`]);
  });

  it.each([
    "Co-Authored-By: Claude Opus 5.5 <noreply@example.com>",
    "co-authored-by: GitHub Copilot <bot@example.com>",
    "Assisted-by: ChatGPT",
    "Generated-by: Codex",
    "Co-authored-by: devin-ai-integration[bot] <158243242+devin@example.com>",
    "Helped-by: Gemini",
    "Co-authored-by: Aider (gpt-5)",
  ])("a trailer naming a tool fails: %s", (line) => {
    expect(check(line)).toHaveLength(1);
  });

  it.each([
    "Signed-off-by: Ada <ada@openai.com>",
    "Co-authored-by: Someone <cursoragent@cursor.com>",
    "Co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>",
    "Co-authored-by: x <copilot@github.com>",
  ])("a vendor's address fails: %s", (line) => {
    expect(check(line)).toHaveLength(1);
  });

  it.each([
    "\u{1F916} Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated by ChatGPT",
    "This change was generated using AI.",
    "Generated via Copilot Workspace",
  ])("a generated-with footer fails: %s", (line) => {
    expect(check(line)).toHaveLength(1);
  });

  it.each([
    "Co-authored-by: Ada Lovelace <ada@example.com>",
    "Co-authored-by: Claude Monet <claude@example.com>",
    "Signed-off-by: Grace Hopper <grace@example.com>",
    "Reviewed-by: Alan Turing <alan@example.com>",
    "on (created_at, id). The cursor is opaque base64url JSON that keeps",
    "verification, the SES error classifier, the migrate CLI, the cursor",
    "Generated database types are written by kysely-codegen.",
    "The types are generated with kysely-codegen from the migrated schema.",
    "Move the copilot of the release to the new owner",
    "",
  ])("ordinary text passes: %s", (line) => {
    expect(check(line)).toEqual([]);
  });

  it("names every failing line of a message, by its number", () => {
    const text = [
      "Fix the thing",
      "",
      "What was wrong and what changed.",
      "",
      "Co-authored-by: Ada Lovelace <ada@example.com>",
      "Co-Authored-By: Claude <noreply@anthropic.com>",
    ].join("\n");

    expect(attributionProblems({ label: "commit 1a2b3c4", text })).toEqual([
      "commit 1a2b3c4 line 6: an AI vendor's address: Co-Authored-By: Claude <noreply@anthropic.com>",
    ]);
  });

  it("checks against the rules it is given", () => {
    const rules = [{ name: "the word nope", pattern: /nope/, example: "nope" }];

    expect(attributionProblems({ label: "x", text: "a\nnope" }, rules)).toEqual([
      "x line 2: the word nope: nope",
    ]);
  });
});

describe("stripGitComments", () => {
  it("drops the lines git comments out for the editor", () => {
    expect(stripGitComments("Subject\n\nBody\n# Please enter the message\n#\tmodified: a")).toBe(
      "Subject\n\nBody",
    );
  });
});

describe("processGit", () => {
  it("returns git's output, and throws with its error when it fails", () => {
    const git = processGit(repository([]));

    expect(git(["rev-parse", "--abbrev-ref", "HEAD"]).trim()).toBe("feature");
    expect(() => git(["rev-parse", "--verify", "no-such-ref"])).toThrow(
      /^git rev-parse --verify no-such-ref failed: fatal: /,
    );
  });

  it("reports a git that writes its error to stdout", () => {
    const git = processGit(tempDir(), "false");

    expect(() => git(["anything"])).toThrow("git anything failed: ");
  });
});

describe("baseRef", () => {
  const known = new Set(["origin/main", "main", "develop"]);
  const git: Git = (args) => {
    const ref = String(args.at(-1)).replace("^{commit}", "");
    if (!known.has(ref)) throw new Error("unknown");
    return "sha\n";
  };

  it("takes the first default branch that exists", () => {
    expect(baseRef(git, {})).toBe("origin/main");
    expect(baseRef(git, { ATTRIBUTION_BASE: " " })).toBe("origin/main");
  });

  it("takes ATTRIBUTION_BASE when set", () => {
    expect(baseRef(git, { ATTRIBUTION_BASE: "develop" })).toBe("develop");
  });

  it("says how to fix a checkout with no default branch", () => {
    expect(() => baseRef(git, { ATTRIBUTION_BASE: "trunk" })).toThrow(
      "cannot find the default branch (tried trunk); fetch it, or set ATTRIBUTION_BASE",
    );
    expect(() => baseRef(() => "", {})).not.toThrow();
  });
});

describe("proposedCommits", () => {
  it("reads every commit from the merge base to HEAD, with its whole message", () => {
    const root = repository([
      "First\n\nIts body.",
      "Second\n\nCo-authored-by: Ada Lovelace <ada@example.com>",
    ]);

    const commits = proposedCommits(processGit(root), "main");

    expect(commits.map((commit) => commit.text.trim())).toEqual([
      "Second\n\nCo-authored-by: Ada Lovelace <ada@example.com>",
      "First\n\nIts body.",
    ]);
    expect(commits[0]?.label).toMatch(/^commit [0-9a-f]{7,}$/);
  });

  it("finds nothing to check on the default branch itself", () => {
    const root = repository([]);
    execFileSync("git", ["switch", "--quiet", "main"], { cwd: root });

    expect(proposedCommits(processGit(root), "main")).toEqual([]);
  });
});

describe("pullRequestMessages", () => {
  it("checks the title and description only when CI passes them", () => {
    expect(pullRequestMessages({})).toEqual([]);
    expect(pullRequestMessages({ PR_TITLE: "Title", PR_BODY: "" })).toEqual([
      { label: "pull request title", text: "Title" },
      { label: "pull request description", text: "" },
    ]);
  });
});

function io(root: string, env: Record<string, string> = {}) {
  const lines: string[] = [];
  return {
    lines,
    io: { ...processIo(root, (line) => lines.push(line)), env },
  };
}

describe("commitAttribution", () => {
  it("passes a branch whose commits and pull request credit no tool", () => {
    const run = io(repository(["One", "Two\n\nCo-authored-by: Ada <ada@example.com>"]), {
      PR_TITLE: "Add things",
      PR_BODY: "What and why.",
    });

    expect(commitAttribution([], run.io)).toBe(0);
    expect(run.lines).toEqual(["commit attribution: 4 checked, none credits an AI tool."]);
  });

  it("fails on a commit that does, naming the commit and the line", () => {
    const root = repository(["Fine", "Add it\n\nGenerated by Codex"]);
    const sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root })
      .toString()
      .trim();
    const run = io(root);

    expect(commitAttribution([], run.io)).toBe(1);
    expect(run.lines[0]).toBe(`commit ${sha} line 3: a generated-with footer: Generated by Codex`);
    expect(run.lines).toHaveLength(2);
  });

  it("fails on a pull request description that does", () => {
    const run = io(repository([]), { PR_BODY: "Summary\n\n\u{1F916} Made by a bot" });

    expect(commitAttribution([], run.io)).toBe(1);
    expect(run.lines[0]).toBe(
      "pull request description line 3: a robot-emoji footer: \u{1F916} Made by a bot",
    );
  });

  it("checks one message file for the commit-msg hook, ignoring git's comments", () => {
    const dir = tempDir();
    const good = path.join(dir, "good");
    const bad = path.join(dir, "bad");
    writeFileSync(good, "Subject\n\n# Co-Authored-By: Claude <noreply@anthropic.com>\n");
    writeFileSync(bad, "Subject\n\nCo-authored-by: Copilot <x@example.com>\n");
    const run = io(dir);

    expect(commitAttribution(["--message-file", good], run.io)).toBe(0);
    expect(commitAttribution(["--message-file", bad], run.io)).toBe(1);
    expect(run.lines).toContain(
      "this commit message line 3: a trailer naming an AI tool: Co-authored-by: Copilot <x@example.com>",
    );
  });

  it("cannot run without its inputs, and says why", () => {
    const run = io(tempDir());

    expect(commitAttribution(["--message-file"], run.io)).toBe(2);
    expect(commitAttribution(["--all"], run.io)).toBe(2);
    expect(commitAttribution([], run.io)).toBe(2);
    expect(run.lines).toEqual([
      "commit attribution: --message-file needs the path of the message",
      "commit attribution: unknown arguments: --all",
      "commit attribution: cannot find the default branch (tried origin/HEAD, origin/main, main); fetch it, or set ATTRIBUTION_BASE",
    ]);
  });

  it("reads this process's environment by default", () => {
    expect(processIo(tempDir(), () => {}).env).toBe(process.env);
  });
});
